          <!-- ─── 环境保护法 ─── -->
          <h4>一、《中华人民共和国环境保护法》要点</h4>
          <p><strong>第一章 总则</strong></p>
          <p>保护和改善环境，防治污染和其他公害，保障公众健康，推进生态文明建设。</p>
          <p>一切单位和个人都有保护环境的义务。企业事业单位和其他生产经营者应当防止、减少环境污染和生态破坏。</p>

          <p><strong>第四章 防治污染和其他公害</strong></p>
          <p>（一）排放污染物的企业事业单位，应当建立环境保护责任制度，明确单位负责人和相关人员的责任。</p>
          <p>（二）重点排污单位应当按照国家有关规定和监测规范安装使用监测设备，保证监测设备正常运行，保存原始监测记录。</p>
          <p>（三）实行排污许可管理的企业事业单位，应当按照排污许可证的要求排放污染物。</p>
          <p>（四）禁止通过暗管、渗井、渗坑、灌注或者篡改、伪造监测数据等逃避监管的方式违法排放污染物。</p>

          <p><strong>第六章 法律责任</strong></p>
          <p>（一）超标排放或超总量排放：责令改正，处10万元以上100万元以下罚款；情节严重的，责令停产整治。</p>
          <p>（二）未依法进行环境影响评价：责令停止建设，处以罚款，可以责令恢复原状。</p>

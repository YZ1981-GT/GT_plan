          <!-- ─── 大气污染防治法 ─── -->
          <h4>二、《中华人民共和国大气污染防治法》要点</h4>
          <p>（一）向大气排放污染物的单位应当按照规定设置大气污染物排放口，禁止无组织排放。</p>
          <p>（二）重点大气污染物排放实行总量控制。排放单位应当取得排污许可证。</p>
          <p>（三）排放工业废气的企业应当安装、使用大气污染物处理设施或采取减排技术措施。</p>
          <p>（四）在大气受到严重污染时，企业应当按照应急预案采取限产、停产等措施。</p>
          <p>（五）VOCs（挥发性有机物）排放须安装净化装置并保证正常使用。</p>

          <!-- ─── 水污染防治法 ─── -->
          <h4>三、《中华人民共和国水污染防治法》要点</h4>
          <p>（一）直接或间接向水体排放工业废水和医疗污水应取得排污许可证。</p>
          <p>（二）禁止利用渗井、渗坑、裂隙、溶洞和私设暗管排放水污染物。</p>
          <p>（三）企业事业单位发生事故或者其他突发性事件，造成或者可能造成水污染事故的，应当立即启动应急方案。</p>
          <p>（四）工业集聚区应当配套建设集中式污水处理设施，安装自动监测设备并与环保部门联网。</p>

          <!-- ─── 固体废物污染环境防治法 ─── -->
          <h4>四、《中华人民共和国固体废物污染环境防治法》要点</h4>
          <p>（一）产生固体废物的单位应当建立管理台账，如实记录固体废物的种类、数量、流向等信息。</p>
          <p>（二）危险废物实行分类管理制度。产生危废的单位必须制定管理计划并向生态环境主管部门备案。</p>
          <p>（三）转移危险废物应当填写危险废物转移联单（电子联单）。</p>
          <p>（四）从事危险废物收集、贮存、利用、处置经营活动的单位应当取得危险废物经营许可证。</p>
          <p>（五）跨省转移固废须经接收地省级生态环境部门同意（危废须经移出地省级审批）。</p>

          <!-- ─── 环境影响评价法 ─── -->
          <h4>五、《中华人民共和国环境影响评价法》要点</h4>
          <p>（一）建设项目的环境影响评价文件未经审批，建设单位不得开工建设。</p>
          <p>（二）建设单位应当在建设项目投入生产或者使用前，对环保设施进行竣工验收（"三同时"制度）。</p>
          <p>（三）规划环评：编制土地利用规划、区域开发和行业规划等，应当进行环境影响评价。</p>
          <p>（四）对环境有重大影响的建设项目，应当编制环境影响报告书；对环境影响较轻的，编制报告表。</p>

          <!-- ─── 环境保护税法 ─── -->
          <h4>六、《中华人民共和国环境保护税法》要点</h4>
          <p>（一）直接向环境排放应税污染物的企业事业单位和其他生产经营者为环境保护税的纳税人。</p>
          <p>（二）应税污染物：大气污染物、水污染物、固体废物、噪声。</p>
          <p>（三）大气和水污染物按排放量折合的污染当量数确定应纳税额。</p>
          <p>（四）纳税人排放应税大气/水污染物浓度值低于标准30%的，减按75%征收；低于50%的减按50%征收。</p>
          <p>（五）纳税义务发生时间为纳税人排放应税污染物的当日，按月计算、按季申报缴纳。</p>

          <!-- ─── 排污许可管理条例 ─── -->
          <h4>七、《排污许可管理条例》要点</h4>
          <p>（一）排污单位应当依法申请取得排污许可证，未取得排污许可证的不得排放污染物。</p>
          <p>（二）排污许可证规定排放的污染物种类、浓度、排放量、排放去向、自行监测等事项。</p>
          <p>（三）排污单位应当按照排污许可证规定和监测方案开展自行监测并保存原始记录。</p>
          <p>（四）排污许可证有效期5年，到期应当申请延续。</p>

          <!-- ─── 审计关注 ─── -->
          <h4>八、审计关注要点</h4>
          <p>（一）被审计单位是否取得并持有有效的排污许可证、环评审批文件。</p>
          <p>（二）实际排放是否超过排污许可证允许的排放浓度和排放总量。</p>
          <p>（三）是否存在未经环评擅自建设/投产运营的项目（"未批先建""未验先投"）。</p>
          <p>（四）环保设施运行费用是否合理入账，是否存在将环保资本支出错误费用化的情况。</p>
          <p>（五）环境修复义务（弃置费用/场地修复）是否已确认为预计负债并合理计量。</p>
          <p>（六）是否存在已发生或潜在的环境诉讼、行政处罚、赔偿责任等或有负债。</p>
          <p>（七）碳排放配额/碳信用的会计处理是否恰当。</p>
          <p>（八）环保罚款、赔偿等是否已在财务报表中恰当列示和披露。</p>
          <p>（九）环保税是否按规定时间申报缴纳，纳税申报数据与排放监测数据是否一致。</p>
          <p>（十）环境信息披露是否真实、准确、完整，是否满足监管要求（ESG/CSR 报告）。</p>
        </div>

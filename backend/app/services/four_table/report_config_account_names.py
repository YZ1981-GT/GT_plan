def head_code(code: str) -> str:
    """取科目码主段，供查 ``account_chart``。

    ``1231-03`` → ``1231``（标准码用横杠分隔明细）；
    ``1231.03`` → ``1231``（客户原始码用点号）；
    ``1401~1499`` → ``1401``（区间口径取起点，仅用于存在性判断）。
    """
    for sep in ("~", "-", "."):
        if sep in code:
            code = code.split(sep, 1)[0]
    return code.strip()

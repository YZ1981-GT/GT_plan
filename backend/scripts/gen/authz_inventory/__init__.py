"""鉴权清单共享包（spec partner-manager-edit-permission，design §4.12）。

供两个正式生成脚本共用：``gen_note_write_inventory.py``（附注写端点清册，需求 1）与
``gen_edit_level_impact_inventory.py``（edit 级影响清单，需求 9.1 / 9.8）。无 ``_`` 前缀 = 正式工具。

模块分工：

- ``routes``：运行时路由表。子进程里导入 ``--root`` 那棵树的 ``app.router_registry``，
  各注册分组建空 ``FastAPI()`` 注册一次，收集每条 ``APIRoute`` 的方法、完整路径、端点函数与四处依赖；
  附注清册的扫描文件；源码声明与路由表对账（未注册的端点）；按端点函数归组。
- ``astmodel`` / ``astscan``：源码静态扫描（数据模型 / 扫描实现）。导入别名、同文件常量、函数单元的签名依赖
  与函数体调用点（条件执行标记、实参静态取值）、模块级路由器与路由装饰器。不认识任何具体门禁。
- ``gates``：门禁登记表 + 端点识别。签名参数默认值、装饰器 / 路由器 ``dependencies=``、
  注册附加依赖（取自路由表）、函数体调用（含同文件辅助函数的间接调用、条件执行标注）；
  级别取字面量或同文件常量；注释 / docstring / 字符串不计；未登记的依赖与无法静态确定的级别报中文问题。
- ``render``：确定性 JSON（键与条目排序、``ensure_ascii=False``、``indent=2``、末尾换行），
  拒绝时间、机器名、绝对路径、行号、浮点数进入产物；检查模式用的逐条比对。
- ``selfcheck``：合成样例框架（样例 = 名称 + 期望结果 + 求实际结果的函数），判错时给出中文的
  「样例名 / 期望 / 实际」清单；两个脚本每次生成 / 检查前先跑各自的样例。
- ``classify``、``frontend``：附注清册的归类与前端调用点扫描（任务 8.2 / 8.3）。

包内模块只依赖标准库与被扫描树的源码文本；只有 ``routes`` 会起子进程导入被扫描树的 ``app``。
调用方（生成脚本、测试）应以 ``-B`` 运行或先置 ``sys.dont_write_bytecode = True``，免得在本包目录落 ``.pyc``。
"""

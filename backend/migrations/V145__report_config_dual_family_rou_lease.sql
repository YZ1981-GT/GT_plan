-- V145: report_config 使用权资产 / 租赁负债 双族并取（additive 加和，零改码）
--
-- 问题（2026-08-06 真实库实证，9 个有 trial_balance 的项目）
-- ----------------------------------------------------------------------------
-- CAS 21 实施过程中平台标准科目表出现两套并存编码族，而 BS-031 / BS-063 的
-- 公式只写了旧族：
--
--   语义                旧族(已写)   新族(未写)   trial_balance.unadjusted_amount 合计
--   使用权资产           1641        1651        160,078.75   vs  386,272,594.21
--   使用权资产累计折旧    1642        1652         68,950.60   vs  246,042,927.81
--   租赁负债             2601        2651         98,176.48   vs  146,970,513.03
--
-- 即按旧族取数只能取到真实金额的 0.04% —— 不是「恒空」而是「取到一个极小的
-- 错数」，比恒空更隐蔽（报表上有值，没人会去核）。
--
-- 为什么是「加和」而不是「改码」
-- ----------------------------------------------------------------------------
-- 逐项目透视实证：两族在**同一项目内互斥**（每个项目只出现一族，另一族为
-- NULL）；唯一两族都有记录的项目 0ec33ac9 双方均为 0.00。
-- ⇒ TB('1641')+TB('1651') 在真实数据上零双算风险，且不动任何现有码。
--
-- 反过来「把 1641 改成 1651」会踩到 V138 已实证的最贵陷阱：把一个零命中码
-- 改成「存在的码」，会让原本靠 fallback 碰巧正确的下游变成活的取数错误；
-- 且旧族在 c8621493 有真实余额 160,078.75，改码会让该项目丢数。
--
-- 为什么新族侧不重复减 2602
-- ----------------------------------------------------------------------------
-- account_mapping 实证：新族把未确认融资费用做成 2651.02 子科目
-- （`2651.02 租赁负债_未确认融资费用 → 2651` auto_exact 5 项目），
-- 即新族下它**已含在 2651 父额内**，再减一次即双算。故 BS-063 只减一次 2602。
--
-- 判据真源：backend/app/services/four_table/dual_family_codes.py
--           （DUAL_FAMILY_ROW_FORMULAS，迁移与守卫共用，禁各写一份）
--
-- 幂等：WHERE 带旧值断言，重复执行命中 0 行；同时防覆盖并发改动。
-- 回滚：R145__rollback_report_config_dual_family_rou_lease.sql
--
-- spec: .kiro/specs/h-cycle-extraction-formula-and-disclosure-completion/
--       Requirements 1.1~1.6 / Property 1~4

-- ── BS-031 使用权资产（四变体）──
UPDATE report_config
SET formula = 'TB(''1641'',''期末余额'')+TB(''1651'',''期末余额'')-TB(''1642'',''期末余额'')-TB(''1652'',''期末余额'')-TB(''1643'',''期末余额'')',
    updated_at = NOW()
WHERE row_code = 'BS-031'
  AND formula = 'TB(''1641'',''期末余额'')-TB(''1642'',''期末余额'')-TB(''1643'',''期末余额'')';

-- ── BS-063 租赁负债（四变体）──
UPDATE report_config
SET formula = 'TB(''2601'',''期末余额'')+TB(''2651'',''期末余额'')-TB(''2602'',''期末余额'')',
    updated_at = NOW()
WHERE row_code = 'BS-063'
  AND formula = 'TB(''2601'',''期末余额'')-TB(''2602'',''期末余额'')';

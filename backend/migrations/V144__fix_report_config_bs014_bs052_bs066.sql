-- BS-014 其他流动资产 → NULL。
-- 现码 1901 实为**待处理财产损溢 / 待处理财产损益**（standard 8 / client 5 项目），
-- tb_balance 该科目族全库 12 行 6 项目期初期末合计恒 0.00；
-- listed_standalone 变体另加的 TB('1131') 应收股利已由 BS-009 认领 = 跨行双算。
-- 「其他流动资产」科目名在全库 account_chart 零命中 ⇒ 无可改指的码。
UPDATE report_config
SET formula = NULL,
    updated_at = NOW()
WHERE row_code = 'BS-014'
  AND formula LIKE '%''1901''%'
  AND applicable_standard NOT LIKE 'project:%'
  AND is_deleted = false;

-- BS-052 一年内到期的非流动负债 → NULL。
-- 现码 2501 实为**长期借款**（standard 8 / client 5 项目），且已由 BS-061 认领 → 跨行双算。
-- 该语义是各非流动负债「一年内到期部分」的重分类合计（客户侧实证散落在
-- 2501.02 / 2651.99 / 2701.99 三个不同父科目下），顶层无对应科目。
-- 与 V138 的 BS-013 / BS-053 完全同型。
UPDATE report_config
SET formula = NULL,
    updated_at = NOW()
WHERE row_code = 'BS-052'
  AND formula LIKE '%''2501''%'
  AND applicable_standard NOT LIKE 'project:%'
  AND is_deleted = false;


-- ───────────────────────────────────────────────────────────────────────────
-- 二、改码
-- ───────────────────────────────────────────────────────────────────────────

-- BS-066 递延收益：现码 2811 **码与名均零命中**（account_chart / tb_balance /
-- trial_balance 三处皆 0 行）⇒ 该行取数恒空。
-- 「递延收益」实际挂在 2401（standard 9 / client 6 项目；tb_balance 16 行 /
-- trial_balance 8 行有数据）。2401 在 report_config 此前零认领 ⇒ 不产生新双算。
-- 🔴 第二写入路径（report_formula_service）侧一直就是 2401（正确）——
--    本迁移是把 report_config **对齐到** filler，不是反过来。
UPDATE report_config
SET formula = REPLACE(formula, '''2811''', '''2401'''),
    updated_at = NOW()
WHERE row_code = 'BS-066'
  AND formula LIKE '%''2811''%'
  AND applicable_standard NOT LIKE 'project:%'
  AND is_deleted = false;



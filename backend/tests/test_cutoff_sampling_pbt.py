# Strategy for voucher entry dictionaries
@st.composite
def st_voucher_entries(draw):
    """Generate a list of voucher entries for stats calculation testing."""
    entries = draw(
        st.lists(
            st.fixed_dictionaries({
                "debit_amount": st.one_of(
                    st.none(),
                    st.decimals(
                        min_value=Decimal("0.01"),
                        max_value=Decimal("9999999.99"),
                        places=2,
                        allow_nan=False,
                        allow_infinity=False,
                    ),
                ),
                "credit_amount": st.one_of(
                    st.none(),
                    st.decimals(
                        min_value=Decimal("0.01"),
                        max_value=Decimal("9999999.99"),
                        places=2,
                        allow_nan=False,
                        allow_infinity=False,
                    ),
                ),
                "voucher_type": st.sampled_from(["记", "收", "付", "转", None]),
            }),
            min_size=0,
            max_size=50,
        )
    )
    return entries


class TestProperty5StatsAccuracy:
    """**Validates: Requirements 2.9**

    For any query result set, the StatsResult SHALL satisfy:
    - debit_total == sum of all debit_amount (NULL as 0)
    - credit_total == sum of all credit_amount (NULL as 0)
    - sum(by_voucher_type.values()) == total_count
    """

    @settings(max_examples=100)
    @given(entries=st_voucher_entries())
    def test_stats_computation_accuracy(self, entries: list[dict[str, Any]]):
        """**Validates: Requirements 2.9**

        Test pure stats calculation logic:
        debit_total = sum(debit), credit_total = sum(credit), by_type counts match.
        """
        # Compute expected stats
        total_count = len(entries)
        expected_debit = sum(
            e["debit_amount"] for e in entries if e["debit_amount"] is not None
        )
        expected_credit = sum(
            e["credit_amount"] for e in entries if e["credit_amount"] is not None
        )

        # Compute by_voucher_type
        expected_by_type: dict[str, int] = {}
        for e in entries:
            key = e["voucher_type"] if e["voucher_type"] is not None else "未分类"
            expected_by_type[key] = expected_by_type.get(key, 0) + 1

        # Build StatsResult matching the computation logic in execute_with_stats
        stats = StatsResult(
            total_count=total_count,
            debit_total=expected_debit,
            credit_total=expected_credit,
            by_voucher_type=expected_by_type,
            truncated=total_count > 500,
        )

        # Assert properties
        assert stats.total_count == total_count
        assert stats.debit_total == expected_debit
        assert stats.credit_total == expected_credit
        assert sum(stats.by_voucher_type.values()) == total_count, (
            f"Sum of by_voucher_type counts ({sum(stats.by_voucher_type.values())}) "
            f"must equal total_count ({total_count})"
        )

        # Each voucher type key corresponds to entries with that type
        for vtype, count in stats.by_voucher_type.items():
            if vtype == "未分类":
                actual = sum(1 for e in entries if e["voucher_type"] is None)
            else:
                actual = sum(1 for e in entries if e["voucher_type"] == vtype)
            assert count == actual, (
                f"by_voucher_type['{vtype}'] = {count} but actual count = {actual}"
            )



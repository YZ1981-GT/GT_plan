class TestProperty6TruncationThreshold:
    """**Validates: Requirements 2.10**

    > 500 → truncated=true + items <= 500
    <= 500 → truncated=false + items == total_count
    """

    @settings(max_examples=100)
    @given(total_count=st.integers(min_value=0, max_value=1000))
    def test_truncation_behavior(self, total_count: int):
        """**Validates: Requirements 2.10**

        Test truncation threshold logic as a pure property:
        - total > 500 → truncated=True, items capped at 500
        - total <= 500 → truncated=False, items == total
        """
        max_total = 500

        # Simulate the truncation logic from execute_with_stats
        truncated = total_count > max_total
        if truncated:
            returned_items_count = min(total_count, max_total)
        else:
            returned_items_count = total_count

        # Assert properties
        if total_count > 500:
            assert truncated is True, (
                f"total_count={total_count} > 500 must set truncated=True"
            )
            assert returned_items_count <= 500, (
                f"When truncated, items count ({returned_items_count}) must be <= 500"
            )
        else:
            assert truncated is False, (
                f"total_count={total_count} <= 500 must set truncated=False"
            )
            assert returned_items_count == total_count, (
                f"When not truncated, items count ({returned_items_count}) "
                f"must equal total_count ({total_count})"
            )



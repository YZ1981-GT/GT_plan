class TestProperty4QueryFilterConstruction:
    """**Validates: Requirements 1.4, 2.4, 2.6, 2.7, 2.8**

    Each filter field correctly maps to SQL clause presence/absence.
    """

    @pytest.mark.asyncio
    @settings(max_examples=100)
    @given(filters=st_ledger_query_filters())
    async def test_filter_fields_map_to_sql_clauses(
        self, filters: LedgerQueryFilters
    ):
        """**Validates: Requirements 1.4, 2.4, 2.6, 2.7, 2.8**

        Each filter field in LedgerQueryFilters correctly maps to SQL clause
        presence or absence.
        """
        project_id = uuid.uuid4()
        year = 2025
        mock_db = AsyncMock()

        from app.models.audit_platform_models import TbLedger

        mock_filter = sa.and_(
            TbLedger.project_id == project_id,
            TbLedger.year == year,
            TbLedger.is_deleted == sa.false(),
        )

        with patch(
            "app.services.ledger_sampling_service.get_active_filter",
            new=AsyncMock(return_value=mock_filter),
        ):
            query = await LedgerSamplingService.build_ledger_query(
                db=mock_db,
                project_id=project_id,
                year=year,
                filters=filters,
            )

        compiled = query.compile(
            compile_kwargs={"literal_binds": True},
            dialect=sa.dialects.postgresql.dialect(),
        )
        sql_str = str(compiled).lower()

        # 1. account_codes → LIKE prefix conditions
        if filters.account_codes:
            for code in filters.account_codes:
                assert f"like '{code}%" in sql_str or f"like '{code.lower()}%" in sql_str, (
                    f"account_code prefix '{code}%' must appear in SQL. Got: {sql_str}"
                )

        # 2. direction_filter mapping
        # Check that the WHERE clause contains the specific direction condition
        if filters.direction_filter == "debit":
            assert "tb_ledger.debit_amount > 0" in sql_str, (
                f"debit direction must add 'debit_amount > 0'. Got: {sql_str}"
            )
        elif filters.direction_filter == "credit":
            assert "tb_ledger.credit_amount > 0" in sql_str, (
                f"credit direction must add 'credit_amount > 0'. Got: {sql_str}"
            )

        # 3. amount_threshold > 0 → greatest/coalesce condition
        if filters.amount_threshold > 0:
            assert "greatest" in sql_str, (
                f"Non-zero threshold must add GREATEST condition. Got: {sql_str}"
            )
            assert "coalesce" in sql_str, (
                f"Non-zero threshold must use COALESCE. Got: {sql_str}"
            )

        # 4. summary_keyword → ILIKE condition
        if filters.summary_keyword:
            assert "ilike" in sql_str or "like" in sql_str, (
                f"Non-empty keyword must add ILIKE/LIKE condition. Got: {sql_str}"
            )
            assert filters.summary_keyword.lower() in sql_str, (
                f"Keyword '{filters.summary_keyword}' must appear in SQL. Got: {sql_str}"
            )

        # 5. voucher_type_filter → IN condition
        if filters.voucher_type_filter:
            assert "voucher_type" in sql_str and "in" in sql_str, (
                f"voucher_type_filter must add IN condition. Got: {sql_str}"
            )

        # 6. exclude_voucher_nos → NOT IN condition
        if filters.exclude_voucher_nos:
            assert "voucher_no" in sql_str and "not in" in sql_str, (
                f"exclude_voucher_nos must add NOT IN condition. Got: {sql_str}"
            )



class TestProperty9ExcludeExtractedDedup:
    """**Validates: Requirements 2.12**

    After filtering, result ∩ extracted = ∅; all non-extracted items preserved.
    """

    @settings(max_examples=100)
    @given(
        extracted_nos=st.lists(
            st.text(min_size=1, max_size=20, alphabet="0123456789-ABCabc"),
            min_size=0,
            max_size=30,
        ),
        query_result_nos=st.lists(
            st.text(min_size=1, max_size=20, alphabet="0123456789-ABCabc"),
            min_size=0,
            max_size=30,
        ),
    )
    def test_exclude_extracted_dedup(
        self,
        extracted_nos: list[str],
        query_result_nos: list[str],
    ):
        """**Validates: Requirements 2.12**

        When exclude_extracted=True:
        - Filtered result has no overlap with extracted set
        - All non-extracted items from query result are preserved (no false exclusions)
        """
        extracted_set = set(extracted_nos)

        # Simulate the exclusion logic: filter out voucher_nos in extracted set
        filtered_result = [
            no for no in query_result_nos if no not in extracted_set
        ]

        # Property 1: intersection with extracted must be empty
        filtered_set = set(filtered_result)
        intersection = filtered_set & extracted_set
        assert intersection == set(), (
            f"Filtered result must not contain extracted voucher_nos. "
            f"Intersection: {intersection}"
        )

        # Property 2: all non-extracted items from query result must be preserved
        expected_preserved = [
            no for no in query_result_nos if no not in extracted_set
        ]
        assert filtered_result == expected_preserved, (
            f"All non-extracted items must be preserved in order. "
            f"Expected: {expected_preserved}, Got: {filtered_result}"
        )

        # Property 3: no false exclusions — every item in query_result that
        # is NOT in extracted must appear in filtered
        non_extracted_from_query = {no for no in query_result_nos if no not in extracted_set}
        assert non_extracted_from_query <= filtered_set, (
            f"Some non-extracted items were falsely excluded. "
            f"Missing: {non_extracted_from_query - filtered_set}"
        )

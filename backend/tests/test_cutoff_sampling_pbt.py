# Strategy for account codes (1-6 digit prefixes)
st_account_codes = st.lists(
    st.text(
        alphabet="0123456789",
        min_size=1,
        max_size=6,
    ),
    min_size=1,
    max_size=5,
)

# Strategy for direction_filter
st_direction = st.sampled_from(["debit", "credit", "all"])

# Strategy for amount threshold
st_threshold = st.decimals(
    min_value=Decimal("0"),
    max_value=Decimal("999999999.99"),
    places=2,
    allow_nan=False,
    allow_infinity=False,
)

# Strategy for summary keyword
# 关键词取真实搜索字符集：断言 #4 校验关键词逐字出现在 literal_binds 渲染的 SQL 中，
# 而反斜杠会被 PostgreSQL 字面量渲染转义为双反斜杠、单引号会被转义为两个单引号，
# 使「逐字子串」判定对这两类字符不成立（属断言前提而非产品缺陷）。故排除 \ 与 '。
# 说明：`summary.ilike('%<kw>%')` 未转义 LIKE 元字符(%/_/\)是独立的既有产品加固项。
st_keyword = st.one_of(
    st.just(""),
    st.text(
        alphabet="abcdeABCDE01234 -采购付款销售转账费用工程往来",
        min_size=1,
        max_size=10,
    ),
)

# Strategy for voucher type filter
st_voucher_types = st.lists(
    st.sampled_from(["记", "收", "付", "转"]),
    min_size=0,
    max_size=4,
    unique=True,
)

# Strategy for exclude voucher nos
st_exclude_nos = st.lists(
    st.text(min_size=1, max_size=20, alphabet="0123456789-"),
    min_size=0,
    max_size=10,
)


@st.composite
def st_ledger_query_filters(draw):
    """Composite strategy for LedgerQueryFilters."""
    base_date = draw(st.dates(min_value=date(2020, 1, 1), max_value=date(2030, 12, 31)))
    days_range = draw(st.integers(min_value=1, max_value=60))
    end_date = base_date + timedelta(days=days_range)

    return LedgerQueryFilters(
        date_start=base_date,
        date_end=end_date,
        account_codes=draw(st_account_codes),
        amount_threshold=draw(st_threshold),
        direction_filter=draw(st_direction),
        voucher_type_filter=draw(st_voucher_types),
        summary_keyword=draw(st_keyword),
        exclude_voucher_nos=draw(st_exclude_nos),
    )


